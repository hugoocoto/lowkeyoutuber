def parse_flow(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError(f"{path}: missing the --- header ---")
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    for k in ("name", "summary", "status"):
        if not meta.get(k):
            raise ValueError(f"{path}: header needs '{k}'")
    if meta["name"] != os.path.splitext(os.path.basename(path))[0]:
        raise ValueError(f"{path}: name must match the file name")
    meta["inputs"] = [x.strip() for x in meta.get("inputs", "").split(";") if x.strip()]
    meta["script"] = meta.get("script", "no") == "yes"
    meta["file"] = os.path.relpath(path, HERE)
    meta["body"] = text[m.end():]
    return meta


def flows():
    return [parse_flow(os.path.join(FLOWS_DIR, f)) for f in sorted(os.listdir(FLOWS_DIR)) if f.endswith(".md")]


def cmd_flows(args):
    fl = flows()
    data = [{k: v for k, v in f.items() if k != "body"} for f in fl]
    width = max(len(f["name"]) for f in fl)
    text = "\n".join(f"{f['name']:<{width}}  [{f['status']}]  {f['summary']}\n{'':<{width}}  needs: "
                     + "; ".join(f["inputs"]) for f in fl)
    text += "\n\nExamples, not rules: read one that is close to the request, then adapt it or combine the " \
            "tools your own way (AGENTS.md lists them). Status: ready = every step has a tool; partial = some " \
            "steps are done by hand; planned = not usable yet."
    out(data, args.json, text)


SKILL_NAME = "lowkeyoutuber"
SKILL_MARK = "<!-- generated by ./lky skills -->"


def skill_text(fl):
    """The one skill: point the agent at the tools; the flows are listed as examples only."""
    examples = "\n".join(f"- `{f['file']}` ({f['status']}): {f['summary']}" for f in fl)
    description = json.dumps(
        "Make or edit videos with this repo's tools: cut and polish recordings, Shorts, narration (TTS), "
        "animated scenes, app captures, teleprompter takes, subtitles, titles, thumbnails, uploads. Use when "
        "the user asks for any video work in this repo.", ensure_ascii=False)
    return (f"---\nname: {SKILL_NAME}\ndescription: {description}\n---\n{SKILL_MARK}\n\n"
            "Read `AGENTS.md` first if you haven't in this session: it lists the tools, the project folder and "
            "the person's preferences. Combine the tools however the request needs; `./lky backends` shows "
            "which models work on this machine.\n\n"
            "Worked examples (read one that is close to the request and adapt it; they are not rules):\n\n"
            f"{examples}\n")


def cmd_skills(args):
    # drop skills an older version generated (one per flow), keep anything written by hand
    for name in os.listdir(SKILLS_DIR) if os.path.isdir(SKILLS_DIR) else []:
        f = os.path.join(SKILLS_DIR, name, "SKILL.md")
        if name != SKILL_NAME and os.path.isfile(f):
            with open(f, encoding="utf-8") as fh:
                text = fh.read()
            if "lowkeyoutuber flow:" in text and "in this repository exactly, step by step" in text:
                shutil.rmtree(os.path.join(SKILLS_DIR, name))
    d = os.path.join(SKILLS_DIR, SKILL_NAME)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "SKILL.md"), "w", encoding="utf-8") as fh:
        fh.write(skill_text(flows()))
    written = [os.path.relpath(os.path.join(d, "SKILL.md"), HERE)]
    out(written, args.json, "\n".join(written))


