VIDEO_EXT = (".mp4", ".mkv", ".mov", ".webm", ".avi")
AUDIO_EXT = (".wav", ".mp3", ".flac", ".ogg", ".m4a", ".opus")
IMAGE_EXT = (".png", ".jpg", ".jpeg", ".webp", ".bmp")


def out(data, as_json, text):
    if as_json:
        json.dump(data, sys.stdout, ensure_ascii=False, indent=2)
        print()
    else:
        print(text)


